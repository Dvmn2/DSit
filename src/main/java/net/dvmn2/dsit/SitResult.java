package net.dvmn2.dsit;

/**
 * Результат попытки посадить/удержать игрока.
 */
public enum SitResult {
    SUCCESS,
    /** Отменено через {@link net.dvmn2.dsit.event.PlayerSitEvent}. */
    CANCELLED,
    /** Сам игрок сейчас не может сесть (уже сидит, едет, спит и т.д.). */
    SELF_BUSY,
    /** Место или целевой игрок заняты/недоступны. */
    TARGET_BUSY,
    /** Здесь нельзя сесть (нет опоры, вода, нет места над головой). */
    INVALID_LOCATION,
    /** Игрок уже в этом состоянии (для /grab). */
    ALREADY,
    /** Не удалось посадить на сущность-сиденье. */
    FAILED
}

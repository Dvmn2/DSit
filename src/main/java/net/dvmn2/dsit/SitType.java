package net.dvmn2.dsit;

/**
 * Способ, которым игрок оказался на сиденье.
 */
public enum SitType {
    /** Команда /sit: сидение на месте, где стоит игрок. */
    COMMAND,
    /** ПКМ по блоку (ступеньки, плиты и т.д.). */
    BLOCK,
    /** ПКМ по другому игроку: сидение у него на голове. */
    PLAYER,
    /** Принудительное удержание командой /grab. */
    GRAB
}
